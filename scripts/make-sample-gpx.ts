/**
 * Generates public/samples/sample-hike.gpx: a synthetic out-and-back hike above Grindelwald
 * (Switzerland) with switchbacks, a lunch stop and realistic GPS noise. Synthetic on purpose, so
 * the repo contains nobody's real location history.
 *
 * Run with: pnpm sample:gpx
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ORIGIN = { lat: 46.6242, lon: 8.0414 };
const START = Date.parse('2026-07-18T07:30:00Z');
const SAMPLE_S = 5;
const M_PER_DEG_LAT = 111_195;
const M_PER_DEG_LON = M_PER_DEG_LAT * Math.cos((ORIGIN.lat * Math.PI) / 180);

// Deterministic PRNG (mulberry32) + Box-Muller, so the file is reproducible.
let seed = 42;
function random() {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const gaussian = () => Math.sqrt(-2 * Math.log(1 - random())) * Math.cos(2 * Math.PI * random());
const smoothstep = (s: number) => s * s * (3 - 2 * s);

interface P {
  x: number;
  y: number;
  ele: number;
}

/** Outbound: valley walk, then switchbacks up the slope, then a ridge traverse. */
function outbound(s: number): P {
  const switchbacks = s > 0.25 && s < 0.75 ? Math.sin(((s - 0.25) / 0.5) * Math.PI) : 0;
  return {
    x: 1400 * s + 180 * switchbacks * Math.sin(2 * Math.PI * 9 * s),
    y: 3200 * smoothstep(s),
    ele: 1050 + 820 * smoothstep(Math.min(1, s * 1.15)),
  };
}

/** Return: a wider arc down the other side of the valley. */
function inbound(s: number): P {
  const out = outbound(1 - s);
  return { x: out.x * 0.95 + 650 * Math.sin(Math.PI * s), y: out.y, ele: out.ele };
}

/** Walks a path at a slope-dependent hiking speed, emitting one point every SAMPLE_S seconds. */
function walk(path: (s: number) => P, t0: number): { p: P; t: number }[] {
  const fine = Array.from({ length: 20_001 }, (_, i) => path(i / 20_000));
  const out: { p: P; t: number }[] = [];
  let t = t0;
  let carry = 0;
  for (let i = 1; i < fine.length; i++) {
    const a = fine[i - 1]!;
    const b = fine[i]!;
    const d = Math.hypot(b.x - a.x, b.y - a.y);
    const grade = d > 0 ? (b.ele - a.ele) / d : 0;
    // Tobler's hiking function, in m/s.
    const speed = (6 * Math.exp(-3.5 * Math.abs(grade + 0.05)) * 1000) / 3600;
    carry += d / speed;
    while (carry >= SAMPLE_S) {
      carry -= SAMPLE_S;
      t += SAMPLE_S;
      out.push({ p: b, t });
    }
  }
  return out;
}

const samples = [{ p: outbound(0), t: 0 }, ...walk(outbound, 0)];
const summit = samples.at(-1)!;
// 12-minute lunch stop at the top: the watch keeps recording a stationary position.
for (let k = 1; k <= (12 * 60) / SAMPLE_S; k++)
  samples.push({ p: summit.p, t: summit.t + k * SAMPLE_S });
samples.push(...walk(inbound, samples.at(-1)!.t));

// GPS noise is correlated over time, so use a slowly drifting offset plus a little jitter.
let driftX = 0;
let driftY = 0;
const trkpts = samples.map(({ p, t }) => {
  driftX = 0.9 * driftX + 0.6 * gaussian();
  driftY = 0.9 * driftY + 0.6 * gaussian();
  const lat = ORIGIN.lat + (p.y + driftY + 0.5 * gaussian()) / M_PER_DEG_LAT;
  const lon = ORIGIN.lon + (p.x + driftX + 0.5 * gaussian()) / M_PER_DEG_LON;
  const ele = p.ele + 1.2 * gaussian();
  const time = new Date(START + t * 1000).toISOString().replace('.000Z', 'Z');
  return `      <trkpt lat="${lat.toFixed(6)}" lon="${lon.toFixed(6)}"><ele>${ele.toFixed(1)}</ele><time>${time}</time></trkpt>`;
});

const gpx = `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="OpenFlyover sample generator" xmlns="http://www.topografix.com/GPX/1/1">
  <metadata>
    <name>Sample hike above Grindelwald</name>
    <desc>Synthetic activity generated by scripts/make-sample-gpx.ts. Not a real recording.</desc>
  </metadata>
  <trk>
    <name>Sample hike above Grindelwald</name>
    <type>hiking</type>
    <trkseg>
${trkpts.join('\n')}
    </trkseg>
  </trk>
</gpx>
`;

const out = fileURLToPath(new URL('../public/samples/sample-hike.gpx', import.meta.url));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, gpx);
console.log(`Wrote ${trkpts.length} points to ${out}`);
